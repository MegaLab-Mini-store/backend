CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR(255) UNIQUE,
    name VARCHAR(255) NOT NULL,
    purchase_price BIGINT NOT NULL,
    sale_price BIGINT NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE deliveries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    client_uuid VARCHAR(255) UNIQUE,
    supplier_info VARCHAR(255),
    total_amount BIGINT NOT NULL DEFAULT 0,
    occurred_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE delivery_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    purchase_price BIGINT NOT NULL
);

CREATE TABLE loyalty_levels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    cashback_percentage INTEGER NOT NULL
);

CREATE TABLE clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_code VARCHAR(255) NOT NULL UNIQUE,
    telegram_id BIGINT UNIQUE,
    name VARCHAR(255),
    phone VARCHAR(255),
    loyalty_level_id INTEGER NOT NULL,
    bonus_balance BIGINT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE sales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    client_id INTEGER,
    client_uuid VARCHAR(255) UNIQUE,
    replaces_client_uuid VARCHAR(255),
    total_amount BIGINT NOT NULL,
    payment_method VARCHAR(255) NOT NULL,
    bonus_spent BIGINT NOT NULL DEFAULT 0,
    paid_amount BIGINT NOT NULL DEFAULT 0,
    earned_bonuses BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(255) NOT NULL DEFAULT 'completed',
    occurred_at TIMESTAMPTZ,
    original_occurred_at TIMESTAMPTZ,
    clock_skew_detected BOOLEAN NOT NULL DEFAULT false,
    late_sync BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE sale_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price BIGINT NOT NULL,
    subtotal BIGINT NOT NULL
);

CREATE TABLE inventory_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL,
    operation_type VARCHAR(255) NOT NULL,
    quantity_change INTEGER NOT NULL,
    reference_id INTEGER,
    reason VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE debts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    sale_id INTEGER UNIQUE,
    initial_amount BIGINT NOT NULL,
    remaining_amount BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    reminder_date DATE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE TABLE debt_payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debt_id INTEGER NOT NULL,
    client_uuid VARCHAR(255) UNIQUE,
    amount BIGINT NOT NULL,
    payment_method VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE bonus_transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL,
    sale_id INTEGER,
    amount BIGINT NOT NULL,
    operation_type VARCHAR(255) NOT NULL,
    base_type VARCHAR(255),
    base_amount BIGINT,
    percent INTEGER,
    rounding VARCHAR(255),
    bonus_value INTEGER,
    rules_snapshot JSONB,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE daily_summaries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_date DATE NOT NULL UNIQUE,
    sales_count INTEGER NOT NULL DEFAULT 0,
    total_sales_amount BIGINT NOT NULL DEFAULT 0,
    total_purchases_amount BIGINT NOT NULL DEFAULT 0,
    cash_sales_amount BIGINT NOT NULL DEFAULT 0,
    card_sales_amount BIGINT NOT NULL DEFAULT 0,
    debt_sales_amount BIGINT NOT NULL DEFAULT 0,
    bonus_paid_amount BIGINT NOT NULL DEFAULT 0,
    bonuses_earned BIGINT NOT NULL DEFAULT 0,
    debt_payments_amount BIGINT NOT NULL DEFAULT 0,
    cash_debt_payments_amount BIGINT NOT NULL DEFAULT 0,
    card_debt_payments_amount BIGINT NOT NULL DEFAULT 0,
    voided_count INTEGER NOT NULL DEFAULT 0,
    voided_amount BIGINT NOT NULL DEFAULT 0,
    initial_cash_drawer BIGINT NOT NULL DEFAULT 0,
    calculated_cash_drawer BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE TABLE refresh_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    rotated_at TIMESTAMPTZ,
    grace_until TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE loyalty_settings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accrual_base VARCHAR(255) NOT NULL,
    rounding VARCHAR(255) NOT NULL,
    max_redeem_percent INTEGER NOT NULL,
    accrual_moment VARCHAR(255) NOT NULL DEFAULT 'on_sale',
    bonus_value INTEGER NOT NULL DEFAULT 1,
    bonus_expiry_days INTEGER,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE debt_reminders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debt_id INTEGER NOT NULL,
    remind_at TIMESTAMPTZ NOT NULL,
    note TEXT,
    is_done BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ
);

CREATE TABLE corrections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    client_uuid VARCHAR(255) UNIQUE,
    correction_type VARCHAR(255) NOT NULL,
    sale_id INTEGER,
    product_id INTEGER,
    quantity_change INTEGER,
    new_payment_method VARCHAR(255),
    reason TEXT NOT NULL,
    old_value TEXT,
    new_value TEXT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE sync_operations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_uuid VARCHAR(255) NOT NULL UNIQUE,
    operation_type VARCHAR(255) NOT NULL,
    payload_hash VARCHAR(255) NOT NULL,
    payload JSONB,
    status VARCHAR(255) NOT NULL,
    server_record_id INTEGER,
    error_code VARCHAR(255),
    error_message TEXT,
    resolution_status VARCHAR(255),
    resolution_note TEXT,
    replacement_client_uuid VARCHAR(255),
    resolved_by INTEGER,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    processed_at TIMESTAMPTZ
);

CREATE TABLE cash_day_closures (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_summary_id INTEGER NOT NULL UNIQUE,
    business_date DATE NOT NULL UNIQUE,
    closed_by INTEGER NOT NULL,
    closed_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'closed',
    initial_cash_drawer BIGINT NOT NULL,
    calculated_cash_drawer BIGINT NOT NULL
);

